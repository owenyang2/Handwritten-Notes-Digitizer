#!/usr/bin/env python3
"""Download a pinned UniMERNet-small snapshot for formula recognition.

This only downloads files. Load them with the upstream UniMERNet code; do not
rename the weights to base_model.pt (that path is the CRNN artifact).
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

# Recorded 2026-09-10 from the public model card; re-resolve before production use.
UNIMERNET_SMALL_REPO = "wanderkid/unimernet_small"
UNIMERNET_SMALL_REVISION = "main"


def _tree_sha256(root: Path) -> str:
    hasher = hashlib.sha256()
    for path in sorted(
        item
        for item in root.rglob("*")
        if item.is_file() and item.name not in {"model_artifact.json", "artifact_manifest.json"}
    ):
        hasher.update(str(path.relative_to(root)).encode("utf-8"))
        hasher.update(hashlib.sha256(path.read_bytes()).hexdigest().encode("ascii"))
    return hasher.hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Download and fingerprint UniMERNet-small")
    parser.add_argument("--destination", type=Path, default=Path("models/unimernet_small"))
    parser.add_argument("--revision", default=UNIMERNET_SMALL_REVISION)
    parser.add_argument("--manifest", type=Path)
    args = parser.parse_args(argv)
    from huggingface_hub import HfApi, snapshot_download

    destination = args.destination
    # Resolve a human-friendly branch/tag to the immutable Hub commit before
    # downloading.  The manifest records the resolved revision so a later
    # replay cannot silently move when ``main`` advances.
    requested_revision = args.revision
    try:
        resolved_revision = str(HfApi().model_info(UNIMERNET_SMALL_REPO, revision=requested_revision).sha)
    except Exception as exc:
        raise SystemExit(f"could not resolve Hugging Face revision {requested_revision!r}: {exc}") from exc
    snapshot_download(
        repo_id=UNIMERNET_SMALL_REPO,
        revision=resolved_revision,
        local_dir=str(destination),
    )
    digest = _tree_sha256(destination)
    manifest_path = args.manifest or destination / "model_artifact.json"
    manifest_path.write_text(json.dumps({
        "backend_id": "unimernet-small",
        "model_id": UNIMERNET_SMALL_REPO,
        "source_url": f"https://huggingface.co/{UNIMERNET_SMALL_REPO}",
        "revision": resolved_revision,
        "requested_revision": requested_revision,
        "weight_sha256": digest,
        "license": "See upstream model card",
        "supported_inputs": ["png", "jpeg", "formula_crop"],
        "notes": "Generated by scripts/download_unimernet.py; use the exact revision for replay.",
    }, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"downloaded {UNIMERNET_SMALL_REPO}@{resolved_revision} to {destination}")
    print(f"artifact digest: {digest}")
    print(f"artifact manifest: {manifest_path}")
    print(f"Use this directory as the configured formula artifact: {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
